"""Generate `dataset/story_rl/traditional_map.json` from the author's published prose.

The map is data, and data generated by hand in a shell is data nobody can re-derive. This script is the only
producer:

    uv run python3 scripts/build_traditional_map.py --corpus "$HOME/Documents/GitHub/Obsidian-note/🚀-PROJECTS/🚀-Active/🎨-Firstory-Platform/06-Story-Works/Posted"

Three exclusions, each owned by `story_rl.traditional` so the rule and the data cannot drift:

    her own characters   whatever she uses is correct by definition, so no rule may rewrite it
    AUTHOR_FORMS         characters she writes in exactly one way; the rule wins, the map must not shadow it
    KEEP / ONE_TO_MANY   valid Traditional forms, and characters whose target depends on the word

Everything else that maps to a single Traditional character, one-to-one, is in the table.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

import zhconv


from story_rl.traditional import AUTHOR_FORMS, KEEP, MAP_PATH, ONE_TO_MANY  # noqa: E402

FRONTMATTER = re.compile(r"^---\n.*?\n---\n", re.DOTALL)
MARKUP = re.compile(r"<[^>]+>")
ENTITY = {"&nbsp;": " ", "&amp;": "&", "&lt;": "<", "&gt;": ">", "&quot;": '"'}
NOT_PROSE = re.compile(r"(企劃書|AO3|audit|AUDIT|AGENT-PROMPT|drift-map|correction-pass|\.meta\.md$)")


def prose_text(posted: Path) -> str:
    """Every manuscript under `posted`, stripped to prose: no YAML, no layout, no chapter titles."""
    pieces: list[str] = []
    for folder in sorted(path for path in posted.iterdir() if path.is_dir()):
        single = folder / f"{folder.name}.md"
        files = [single] if single.exists() else [
            path for path in sorted(folder.glob("*.md")) if not NOT_PROSE.search(path.name)
        ]
        for path in files:
            body = FRONTMATTER.sub("", path.read_text(encoding="utf-8"))
            body = re.sub(r"(?i)<br\s*/?>", "\n", body)
            body = re.sub(r"(?i)</p>", "\n\n", body)
            for raw, replacement in ENTITY.items():
                body = body.replace(raw, replacement)
            body = MARKUP.sub("", body)
            pieces.append("\n".join(line for line in body.splitlines() if not line.startswith(("#", ">"))))
    return "\n".join(pieces)


def build(text: str) -> tuple[dict[str, str], int]:
    used = set(text)
    excluded = used | set(AUTHOR_FORMS) | KEEP | ONE_TO_MANY
    table: dict[str, str] = {}
    for code_point in range(0x4E00, 0x9FA6):
        character = chr(code_point)
        if character in excluded:
            continue
        traditional = zhconv.convert(character, "zh-hant")
        if len(traditional) == 1 and traditional != character:
            table[character] = traditional
    return table, len(used)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--corpus", required=True, help="the directory holding the posted story folders")
    parser.add_argument("--out", default=str(MAP_PATH))
    args = parser.parse_args()

    text = prose_text(Path(args.corpus).expanduser())
    if len(text) < 10_000:
        raise SystemExit(f"corpus too small to derive a character inventory: {len(text)} characters")

    table, distinct = build(text)
    payload = {
        "generated_by": "scripts/build_traditional_map.py",
        "source": "the author's posted manuscripts",
        "author_corpus_characters": len(text),
        "author_distinct_characters": distinct,
        "excluded": {
            "author_usage": "any character she writes",
            "author_forms": sorted(AUTHOR_FORMS),
            "keep": sorted(KEEP),
            "one_to_many": sorted(ONE_TO_MANY),
        },
        "map": dict(sorted(table.items())),
    }
    out = Path(args.out)
    out.write_text(json.dumps(payload, ensure_ascii=False, indent=0) + "\n", encoding="utf-8")
    print(f"{len(table)} mappings from {distinct} distinct characters -> {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
